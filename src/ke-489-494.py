        out.append(f'  <text x="{x + w // 2}" y="88" text-anchor="middle" font-size="12" fill="{c}">{t}</text>')
        out.append(f'  <text x="{x + w // 2}" y="112" text-anchor="middle" font-size="9.5" fill="#8A8074">{s}</text>')
